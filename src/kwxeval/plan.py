"""Build the run matrix (case x model x initial conditions x reference) as a shell script for the GPU machine.

Only combinations the archives can serve are written; the others are listed as skipped with the reason.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from .run import IC_EARLIEST, MODELS, check_ic_times, forecast_label

DEFAULT_MODELS = ["pangu6", "graphcast_op", "fuxi", "aifs", "aifs_ens", "fcn3", "aurora"]


def _ok(ic: str, init_times) -> str | None:
    try:
        check_ic_times(ic, init_times)
        return None
    except ValueError as e:
        return str(e).split(";")[0]


def build_plan(cases: dict, case_names: list[str], models: list[str] | None = None,
               ics=("era5", "gfs", "ifs"), members: int = 8, ic_files: dict[str, str] | None = None,
               runs: str = "runs", results: str = "results", max_gpu_gb: int = 80) -> tuple[list[str], pd.DataFrame]:
    """Return (shell lines, table of planned/skipped runs).

    ic_files: {case: path} of prepared KIM initial-condition files; adds runs labelled model@kim.
    """
    models = models or DEFAULT_MODELS
    ic_files = ic_files or {}
    lines = ["#!/usr/bin/env bash", "# generated by `kwxeval plan`; run on the GPU machine", "set -euo pipefail", ""]
    rows = []
    for cname in case_names:
        case = cases[cname]
        init = case["init_times"]
        lines.append(f"# ---- {cname}")
        for ic in [*ics, *(["file"] if cname in ic_files else [])]:
            reason = None if ic == "file" else _ok(ic, init)
            for m in models:
                spec = MODELS[m]
                why = reason or (f"needs {spec.gpu_gb} GB GPU" if spec.gpu_gb > max_gpu_gb else None)
                label_ic = "kim" if ic == "file" else ic
                rows.append({"case": cname, "model": m, "ic": label_ic, "label": forecast_label(m, label_ic),
                             "kind": spec.kind, "gpu_gb": spec.gpu_gb, "status": "skip" if why else "run",
                             "reason": why or ""})
                if why:
                    continue
                cmd = f"kwxeval run --case {cname} --models {m} --out {runs}"
                if ic != "era5":
                    cmd += f" --ic {ic}"
                if ic == "file":
                    cmd += f" --ic-path {ic_files[cname]} --ic-name kim"
                if spec.kind == "ens":
                    cmd += f" --members {members}"
                lines.append(cmd)
        lines.append(f"kwxeval truth --case {cname} --out {runs}")
        verify = f"kwxeval verify --case {cname} --runs {runs} --out {results} --persistence"
        lines.append(verify)
        first_valid = pd.to_datetime(init).min()
        if first_valid >= IC_EARLIEST["ifs"]:
            lines.append(f"kwxeval truth --case {cname} --out {runs} --source ifs")
            lines.append(f"kwxeval verify --case {cname} --runs {runs} --out {results} --truth ifs")
        lines.append("")
    return lines, pd.DataFrame(rows)


def write_plan(lines: list[str], path: str | Path) -> Path:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("\n".join(lines) + "\n", encoding="utf-8")
    p.chmod(0o755)
    return p
